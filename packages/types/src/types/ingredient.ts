export type Ingredient = {
  id: string;
  recipeVersionId: string;
  sortOrder: number;
  name: string;
  quantity: number | null;
  unit: string | null;
  notes: string | null;
  isOptional: boolean;
};

export type IngredientInput = Omit<Ingredient, 'id' | 'recipeVersionId'> & {
  /**
   * Optional on input: when a host round-trips an existing version's
   * ingredients (e.g. an edit built from the recipe detail), it may pass
   * the ingredient's existing ID so the server preserves it — instruction
   * `ingredientReferences` (#643) point at these IDs and must not dangle
   * across a version rewrite. Omitted IDs are generated by the database.
   */
  id?: string;
};
